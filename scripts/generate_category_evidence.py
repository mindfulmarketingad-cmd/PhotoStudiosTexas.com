#!/usr/bin/env python3
"""Build data/category-evidence.json: which studios qualify for each statewide category.

Inputs: data/studios.json (Outscraper export), data/website-enrichment.json and
data/website-evidence.json (each studio's own homepage), and optional manual
reviews in data/category-overrides.json ({place_id: {category: {"action":
"exclude"|"include", "reason": str}}}). Run after refreshing any of them:

    python3 scripts/generate_category_evidence.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import categories as cat  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def load(name, default):
    path = ROOT / "data" / name
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else default


def main() -> None:
    studios = load("studios.json", {})["studios"]
    enrich = load("website-enrichment.json", {})
    evid = load("website-evidence.json", {})
    overrides = load("category-overrides.json", {})
    overrides.pop("_about", None)
    out_studios = {}
    counts: Counter = Counter()
    for studio in studios:
        pid = studio["place_id"]
        found = cat.generate_category_evidence(studio, enrich.get(pid), evid.get(pid))
        for cid, ov in (overrides.get(pid) or {}).items():
            if cid.startswith("_"):
                continue
            if ov.get("action") == "exclude":
                found.pop(cid, None)
            elif ov.get("action") == "include":
                found.setdefault(cid, []).insert(0, {"source": "manual review", "text": ov.get("reason", "")[:200]})
        if found:
            out_studios[pid] = {"name": studio["name"], "city": studio["city"], "categories": found}
            counts.update(found.keys())
    payload = {
        "about": "Studios that qualify for each statewide category, with the evidence found. Generated by scripts/generate_category_evidence.py; do not hand-edit (use data/category-overrides.json).",
        "counts": {cid: counts.get(cid, 0) for cid in cat.CAT_IDS},
        "studios": dict(sorted(out_studios.items(), key=lambda kv: (kv[1]["city"].lower(), kv[1]["name"].lower(), kv[0]))),
    }
    (ROOT / "data" / "category-evidence.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(payload["counts"], "studios with any category:", len(out_studios))


if __name__ == "__main__":
    main()
